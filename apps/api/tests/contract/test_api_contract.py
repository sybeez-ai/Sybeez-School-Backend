"""Contract between the backend OpenAPI schema and the web/mobile clients.

`client_calls.json` is generated by tools/apimap.py from the web (apps/web/src) and
mobile (Sybeez-School-App src) API calls. Every call must resolve to a backend route
with the same method, so a renamed or removed endpoint fails CI before it ships.
"""

import json
import re
from datetime import datetime, timezone
from pathlib import Path
from unittest.mock import AsyncMock, MagicMock

import pytest

from src.main import app

CALLS = json.loads((Path(__file__).parent / "client_calls.json").read_text())


@pytest.fixture(scope="module")
def spec():
    return app.openapi()


def _routes(spec):
    out = []
    for path, ops in spec["paths"].items():
        pattern = re.sub(r"\{[^}]+\}", "[^/]+", path.removeprefix("/api/v1"))
        out.append((re.compile(f"^{pattern}/?$"), {m.upper() for m in ops}))
    return out


@pytest.mark.parametrize("call", CALLS, ids=lambda c: f"{c['client']}:{c['method']} {c['path']}")
def test_client_call_exists(spec, call):
    matches = [methods for rx, methods in _routes(spec) if rx.match(call["path"])]
    assert matches, f"{call['client']} calls {call['path']} ({call['source']}) but the backend has no such route"
    assert any(call["method"] in m for m in matches), f"{call['method']} {call['path']} not allowed: {matches}"


def test_me_payload_is_shared_contract(spec):
    props = spec["components"]["schemas"]["MeResponse"]["properties"]
    for field in ("id", "email", "role", "school_id", "is_platform_admin", "portals", "permissions"):
        assert field in props


def test_auth_supports_bearer_refresh_for_mobile(spec):
    assert "post" in spec["paths"]["/api/v1/auth/refresh"]
    assert "get" in spec["paths"]["/api/v1/auth/me"]


def test_collections_have_no_trailing_slash_only_routes(spec):
    bad = [p for p in spec["paths"] if p != "/" and p.endswith("/") and p.rstrip("/") not in spec["paths"]]
    assert not bad, f"clients call these without the slash and get a 307: {bad}"


async def test_release_due_accepts_naive_now():
    from src.modules.alerts import service

    db = MagicMock()
    result = MagicMock()
    result.scalars.return_value.all.return_value = []
    db.execute = AsyncMock(return_value=result)
    out = await service.release_due_deliveries(db, now=datetime(2026, 10, 12, 9, 0))
    assert out == {"released": 0}
    stmt = db.execute.await_args_list[-1].args[0]
    moment = [v for v in stmt.compile().params.values() if isinstance(v, datetime)][0]
    assert moment.tzinfo is not None and moment.utcoffset() == timezone.utc.utcoffset(None)
