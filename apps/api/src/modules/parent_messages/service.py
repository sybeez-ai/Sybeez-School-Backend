"""Parent messages in the parent's own language.

Original notices are never changed. Translations are cached per (notice, language), generated by
Qwen through the AI service, previewable and editable by the author/admin, and read by parents in
the in-app inbox. WhatsApp (Meta Cloud API) is the only outbound channel and is consent-gated.
"""

